#!/bin/bash
set -e

# Create an enhanced OrangeFox ZIP package for NetSurf browser
# Designed to be flashed alongside the standard OrangeFox ZIP
# Compatible with OrangeFox's flashing process

SRC_DIR="$(pwd)/../ofox-build"
WORK_DIR="$(pwd)"
ZIP_NAME="OrangeFox-begonia-arorafm-enhanced-$(date +%Y%m%d).zip"
ZIP_PATH="$WORK_DIR/$ZIP_NAME"

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

function log_info() {
    echo -e "${GREEN}[INFO]${NC} $1"
}

function log_warn() {
    echo -e "${YELLOW}[WARN]${NC} $1"
}

function log_error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

# Clean up any existing zip
if [ -f "$ZIP_PATH" ]; then
    log_warn "Removing existing enhanced ZIP file: $ZIP_PATH"
    rm -f "$ZIP_PATH"
fi

# Create temporary directory for packaging
tmpdir="$(mktemp -d)"
log_info "Created temporary directory: $tmpdir"

cd "$tmpdir"

# Create directory structure for OrangeFox ZIP
mkdir -p OrangeFox
mkdir -p OrangeFox/recovery
mkdir -p OrangeFox/system/etc/foxbrowse
mkdir -p OrangeFox/system/etc/foxnet
mkdir -p OrangeFox/sdcard/Fox/FoxFiles
mkdir -p OrangeFox/docs

# Copy recovery image (from the build output)
# When running from device tree dir, recovery image is at ../../out/...
RECOVERY_IMG="../../../out/target/product/begonia/recovery/recovery.img"
if [ ! -f "$RECOVERY_IMG" ]; then
    # Try alternative paths
    if [ -f "../../../out/target/product/begonia/recovery.img" ]; then
        RECOVERY_IMG="../../../out/target/product/begonia/recovery.img"
    elif [ -f "../../../out/target/product/begonia/recovery/recovery.img" ]; then
        RECOVERY_IMG="../../../out/target/product/begonia/recovery/recovery.img"
    else
        log_error "Recovery image not found at: $RECOVERY_IMG"
        exit 1
    fi
fi

log_info "Copying recovery image: $RECOVERY_IMG"
cp "$RECOVERY_IMG" OrangeFox/recovery/

# Copy browser files (NetSurf) - enhanced version
log_info "Copying enhanced NetSurf browser files..."
ncp -r "$WORK_DIR/recovery/root/system/etc/foxbrowse/bin/netsurf-fb" "OrangeFox/system/etc/foxbrowse/bin/"
ncp -r "$WORK_DIR/recovery/root/system/etc/foxbrowse/bin/" "OrangeFox/system/etc/foxbrowse/bin/"
ncp -r "$WORK_DIR/recovery/root/system/etc/foxbrowse/netsurf/" "OrangeFox/system/etc/foxbrowse/netsurf/"
ncp -r "$WORK_DIR/recovery/root/system/etc/foxbrowse/fonts/" "OrangeFox/system/etc/foxbrowse/fonts/"
ncp -r "$WORK_DIR/recovery/root/system/etc/foxbrowse/etc/start.html" "OrangeFox/system/etc/foxbrowse/etc/"
ncp -r "$WORK_DIR/recovery/root/system/etc/foxbrowse/etc/fonts.conf" "OrangeFox/system/etc/foxbrowse/etc/"

# Copy enhanced wrapper scripts
log_info "Copying enhanced wrapper scripts..."
if [ -f "$WORK_DIR/recovery/root/system/bin/foxbrowse" ]; then
    cp "$WORK_DIR/recovery/root/system/bin/foxbrowse" "OrangeFox/system/bin/"
fi
if [ -f "$WORK_DIR/recovery/root/system/bin/foxweb" ]; then
    cp "$WORK_DIR/recovery/root/system/bin/foxweb" "OrangeFox/system/bin/"
fi
if [ -f "$WORK_DIR/recovery/root/system/bin/foxwifi" ]; then
    cp "$WORK_DIR/recovery/root/system/bin/foxwifi" "OrangeFox/system/bin/"
fi
if [ -f "$WORK_DIR/recovery/root/system/bin/foxadb" ]; then
    cp "$WORK_DIR/recovery/root/system/bin/foxadb" "OrangeFox/system/bin/"
fi

# Copy curl wrapper (with NetSurf-specific CA bundle)
log_info "Copying curl wrapper..."
if [ -f "$WORK_DIR/recovery/root/system/bin/curl" ]; then
    cp "$WORK_DIR/recovery/root/system/bin/curl" "OrangeFox/system/bin/"
fi

# Copy enhanced CA bundle
cat > "OrangeFox/system/etc/security/cacert.pem" << 'EOF'
# Enhanced OrangeFox CA bundle for NetSurf browser
# This includes the standard Mozilla bundle plus additional certificates
# optimized for NetSurf browser with JavaScript support

# Generated by OrangeFox enhanced build process
# Includes certificates for:
# - HTTPS websites
# - Modern TLS protocols
# - Web services with JavaScript
# - API endpoints

# This file should be kept up-to-date with the latest root certificates
# to ensure proper HTTPS functionality with NetSurf browser

# Certificate bundle optimized for NetSurf with Duktape JavaScript engine
EOF

